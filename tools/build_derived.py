#!/usr/bin/env python3
"""Build derived files from the graph data.

Reads data/<version>_sm_epistemic_graph.json and writes
  data/statistics.json   per-step counts (nodes per layer, routes, unexplained observables)
  catalog.md             node, edge and route catalogue of every step
  paper/numbers.tex      \\newcommand macros with the counts used in the paper
  paper/tab_*.tex        LaTeX tables (steps, nodes, final routes, final clusters)

Usage: python3 tools/build_derived.py [version]   (default: latest version in versions.json)
"""
import json, re, sys, os, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
versions = json.load(open(os.path.join(ROOT, 'versions.json')))
ver = sys.argv[1] if len(sys.argv) > 1 else versions['latest']
data = json.load(open(os.path.join(ROOT, 'data', f'v{ver}_sm_epistemic_graph.json')))
NODES, STEPS, REFS = data['nodes'], data['steps'], data['references']

# ---------- helpers ----------
def plain(s):
    return re.sub(r'[\^_]\{([^}]*)\}', r'\1', s or '')

def tex_escape(s):
    return (s.replace('\\', r'\textbackslash{}').replace('&', r'\&').replace('%', r'\%').replace('#', r'\#')
             .replace('$', r'\$').replace('~', r'\textasciitilde{}').replace('_', r'\_').replace('^', r'\^{}'))

def rich2tex(s):
    """^{x} -> \\textsuperscript{x}, _{x} -> \\textsubscript{x}; everything else escaped, Unicode kept (XeLaTeX)."""
    out, i = [], 0
    s = s or ''
    while i < len(s):
        c = s[i]
        if c in '^_' and i + 1 < len(s) and s[i+1] == '{':
            j = s.find('}', i + 2)
            if j < 0:
                out.append(tex_escape(c)); i += 1; continue
            inner = tex_escape(s[i+2:j])
            out.append((r'\textsuperscript{' if c == '^' else r'\textsubscript{') + inner + '}')
            i = j + 1
        else:
            out.append(tex_escape(c) if c in '\\&%#$~_^' else ('\\{' if c == '{' else '\\}' if c == '}' else c))
            i += 1
    return ''.join(out)

def md(s):
    """rich markup -> markdown-ish (HTML sup/sub)."""
    return re.sub(r'\^\{([^}]*)\}', r'<sup>\1</sup>', re.sub(r'_\{([^}]*)\}', r'<sub>\1</sub>', s or ''))

graph_steps = [s for s in STEPS if s['id'] != 'synth']

def step_members(s):
    cls = s.get('clusters', [])
    free = [m for m in s['M'] if not any(c['id'] == m for c in cls)]
    members = [m for c in cls for m in c['members']]
    return free, members

def explained_set(s):
    return {e['t'] for e in s['edges'] if e['k'] == 'm2o' and e.get('st') != 'cand' and not e.get('weak')}

# ---------- statistics ----------
stats = []
for i, s in enumerate(graph_steps, 1):
    free, members = step_members(s)
    allM = free + members
    ex = explained_set(s)
    stats.append({
        'step': i, 'id': s['id'], 'title': plain(s['title']), 'years': s['years'], 'driver': s['driver'], 'driver_label': s.get('driverLabel', ''),
        'state_nodes': len(s['S']), 'model_nodes': len(allM), 'clusters': len(s.get('clusters', [])),
        'effective_nodes_active': sum(1 for m in free if NODES[m]['kind'] == 'eff'),
        'effective_nodes_absorbed': sum(1 for m in members if NODES[m]['kind'] == 'eff'),
        'fundamental_nodes': sum(1 for m in allM if NODES[m]['kind'] == 'fund'),
        'observable_nodes': len(s['O']), 'unexplained_observables': [o for o in s['O'] if o not in ex],
        'and_routes': len(s.get('ands', [])), 'edges': len(s['edges']),
    })
all_ids = set()
for s in STEPS:
    free, members = step_members(s)
    all_ids |= set(s['S']) | set(s['M']) | set(members) | set(s['O'])
first_step = {}
for i, s in enumerate(graph_steps, 1):
    free, members = step_members(s)
    for nid in s['S'] + s['M'] + members + s['O']:
        first_step.setdefault(nid, i)
summary = {
    'version': ver, 'graph_steps': len(graph_steps), 'total_steps': len(STEPS),
    'distinct_nodes': len(all_ids),
    'distinct_by_layer': {L: sum(1 for n in all_ids if NODES[n]['layer'] == L) for L in 'SMO'},
    'references': len(REFS),
    'final_step': stats[-1],
}
json.dump({'summary': summary, 'per_step': stats}, open(os.path.join(ROOT, 'data', 'statistics.json'), 'w'), indent=1, ensure_ascii=False)

# ---------- catalog.md ----------
L = ['# Standard Model Epistemic Graph — catalogue (v%s)\n' % ver,
     'Generated by `tools/build_derived.py` from `data/v%s_sm_epistemic_graph.json`. Rich markup is rendered as HTML sup/sub.\n' % ver,
     '\n## Nodes\n', '\n| id | layer | kind | label | years | first step | badge |', '|---|---|---|---|---|---|---|']
for nid in sorted(all_ids, key=lambda n: ('SMO'.index(NODES[n]['layer']), first_step.get(n, 99), n)):
    n = NODES[nid]
    L.append('| %s | %s | %s | %s | %s | %s | %s |' % (nid, n['layer'], n.get('kind', ''), md(n['label']), n.get('years', ''), first_step.get(nid, ''), n.get('driver', '')))
for i, s in enumerate(graph_steps, 1):
    L.append('\n## Step %d — %s (%s)\n' % (i, md(s['title']), s['years']))
    L.append('Driver: %s\n' % s.get('driverLabel', s['driver']))
    free, members = step_members(s)
    L.append('State: %s  \nModel: %s%s  \nObservable: %s\n' % (', '.join(s['S']), ', '.join(free), (' · clusters: ' + '; '.join(c['id'] + ' ⊃ ' + ','.join(c['members']) for c in s.get('clusters', []))) if s.get('clusters') else '', ', '.join(s['O'])))
    L.append('\n| from | to | kind | status | relation |'); L.append('|---|---|---|---|---|')
    for e in s['edges']:
        L.append('| %s | %s | %s | %s | %s |' % (e['f'], e['t'], e['k'], e.get('st', ''), md(e.get('rel', ''))))
    if s.get('ands'):
        L.append('\nAND routes:\n'); L.append('| legs | target | label | relation |'); L.append('|---|---|---|---|')
        for a in s['ands']:
            legs = ', '.join((l.get('s') or ('group ' + l['g'])) + '(%s)' % l['n'] for l in a['legs'])
            L.append('| %s | %s | %s%s | %s |' % (legs, a['t'], md(a['label']), ' (candidate)' if a.get('cand') else '', md(a.get('rel', ''))))
    for c in s.get('clusters', []):
        for ln in c.get('lineage', []):
            L.append('\nLineage in %s: %s → %s — %s' % (c['id'], ln['f'], ln['t'], md(ln.get('rel', ''))))
L.append('\n## References\n')
for k, v in REFS.items():
    L.append('- **%s**: %s' % (k, v))
open(os.path.join(ROOT, 'catalog.md'), 'w').write('\n'.join(L) + '\n')

# ---------- paper tables ----------
P = os.path.join(ROOT, 'paper')
os.makedirs(P, exist_ok=True)
fin = stats[-1]
numbers = {
    'nGraphSteps': len(graph_steps), 'nSteps': len(STEPS), 'nNodes': len(all_ids),
    'nStateNodes': summary['distinct_by_layer']['S'], 'nModelNodes': summary['distinct_by_layer']['M'], 'nObsNodes': summary['distinct_by_layer']['O'],
    'nRefs': len(REFS), 'nFinalSectors': fin['state_nodes'], 'nFinalClusters': fin['clusters'], 'nFinalFund': fin['fundamental_nodes'],
    'nFinalAbsorbed': fin['effective_nodes_absorbed'], 'nFinalRoutes': fin['and_routes'], 'nFinalObs': fin['observable_nodes'],
    'nFinalUnexplained': len(fin['unexplained_observables']), 'nFinalEdges': fin['edges'],
    'maxEffective': max(x['effective_nodes_active'] for x in stats),
    'nFinalFit': sum(1 for e in graph_steps[-1]['edges'] if e['k'] == 'm2o' and e.get('st') == 'fit'),
    'nAnomalySteps': sum(1 for x in stats if x['driver'] == 'anom'),
    'nPredSteps': sum(1 for x in stats if x['driver'] == 'pred'),
}
with open(os.path.join(P, 'numbers.tex'), 'w') as f:
    for k, v in numbers.items():
        f.write('\\newcommand{\\%s}{%s}\n' % (k, v))

drv = {'found': 'foundation', 'sym': 'symmetry', 'anom': 'anomaly', 'resp': 'model response', 'pred': 'prediction', 'syn': 'clustering'}
with open(os.path.join(P, 'tab_steps.tex'), 'w') as f:
    f.write('\\begingroup\\small\n\\begin{longtable}{@{}r>{\\raggedright\\arraybackslash}p{3.9cm}l>{\\raggedright\\arraybackslash}p{2.9cm}rrrrrr@{}}\n\\caption{The twelve graph steps. S, M, O: nodes per layer (M counts cluster members); R: AND routes; U: observable nodes with no model edge; E: effective interaction nodes outside clusters; F: fundamental vertices.}\\label{tab:steps}\\\\\n')
    f.write('\\toprule\\# & Step & Years & Driver & S & M & O & R & U & E/F\\\\\\midrule\\endfirsthead\n\\toprule\\# & Step & Years & Driver & S & M & O & R & U & E/F\\\\\\midrule\\endhead\n\\bottomrule\\endfoot\n')
    for x in stats:
        f.write('%d & %s & %s & %s & %d & %d & %d & %d & %d & %d/%d\\\\\n' % (x['step'], rich2tex(x['title']), tex_escape(x['years']), drv.get(x['driver'], x['driver']), x['state_nodes'], x['model_nodes'], x['observable_nodes'], x['and_routes'], len(x['unexplained_observables']), x['effective_nodes_active'], x['fundamental_nodes']))
    f.write('\\end{longtable}\n\\endgroup\n')

kindname = {'hilbert': 'Hilbert space', 'uir': 'UIR', 'sector': 'Fock sector', 'frame': 'framework', 'eff': 'effective', 'fund': 'fundamental', 'cand': 'candidate', 'cluster': 'cluster'}
for layer, fname, cap in [('S', 'tab_nodes_S.tex', 'State-layer nodes.'), ('M', 'tab_nodes_M.tex', 'Model-layer nodes.'), ('O', 'tab_nodes_O.tex', 'Observable-layer nodes; badge A = observed before explained, P = predicted before observed, F = calibration.')]:
    ids = sorted([n for n in all_ids if NODES[n]['layer'] == layer], key=lambda n: (first_step.get(n, 99), n))
    with open(os.path.join(P, fname), 'w') as f:
        extra = 'l' if layer != 'S' else 'l'
        f.write('\\begin{longtable}{@{}l>{\\raggedright\\arraybackslash}p{7.6cm}lll@{}}\n\\caption{%s}\\label{tab:nodes%s}\\\\\n' % (cap, layer))
        hdr = 'id & label & %s & years & step\\\\' % ('badge' if layer == 'O' else 'kind')
        f.write('\\toprule %s\\midrule\\endfirsthead\n\\toprule %s\\midrule\\endhead\n\\bottomrule\\endfoot\n' % (hdr, hdr))
        for n in ids:
            d = NODES[n]
            k = d.get('driver', '') if layer == 'O' else kindname.get(d.get('kind', ''), d.get('kind', ''))
            f.write('\\texttt{%s} & %s & %s & %s & %s\\\\\n' % (tex_escape(n), rich2tex(d['label']), k, tex_escape(d.get('years', '')), first_step.get(n, '')))
        f.write('\\end{longtable}\n')

final = graph_steps[-1]
with open(os.path.join(P, 'tab_routes.tex'), 'w') as f:
    f.write('\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{3.2cm}>{\\raggedright\\arraybackslash}p{3.6cm}>{\\raggedright\\arraybackslash}p{7.2cm}@{}}\n\\caption{AND routes of the final step: the occupation-number nodes of the sectors that jointly enter each cluster.}\\label{tab:routes}\\\\\n')
    f.write('\\toprule cluster & legs & relation\\\\\\midrule\\endfirsthead\n\\toprule cluster & legs & relation\\\\\\midrule\\endhead\n\\bottomrule\\endfoot\n')
    for a in final.get('ands', []):
        f.write('\\texttt{%s} & %s%s & %s\\\\\n' % (tex_escape(a['t']), rich2tex(a['label']), ' (candidate)' if a.get('cand') else '', rich2tex(a.get('rel', ''))))
    f.write('\\end{longtable}\n')

with open(os.path.join(P, 'tab_clusters.tex'), 'w') as f:
    f.write('\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{4.2cm}>{\\raggedright\\arraybackslash}p{4.4cm}>{\\raggedright\\arraybackslash}p{3.1cm}>{\\raggedright\\arraybackslash}p{3.1cm}@{}}\n\\caption{The clusters of the final step.}\\label{tab:clusters}\\\\\n')
    f.write('\\toprule cluster (Lagrangian term) & members & absorbed effective nodes & observables reached\\\\\\midrule\\endfirsthead\n\\toprule cluster & members & absorbed & observables\\\\\\midrule\\endhead\n\\bottomrule\\endfoot\n')
    for c in final.get('clusters', []):
        mem = [m for m in c['members'] if NODES[m]['kind'] != 'eff']
        absd = [m for m in c['members'] if NODES[m]['kind'] == 'eff']
        obs = [e['t'] for e in final['edges'] if e['f'] == c['id']]
        f.write('%s & %s & %s & %s\\\\\n' % (rich2tex(NODES[c['id']]['label']), ', '.join('\\texttt{%s}' % tex_escape(m) for m in mem), ', '.join('\\texttt{%s}' % tex_escape(m) for m in absd) or '---', ', '.join('\\texttt{%s}' % tex_escape(o) for o in obs)))
    f.write('\\end{longtable}\n')

print('wrote statistics.json, catalog.md, paper tables; summary:', json.dumps(summary['final_step'], ensure_ascii=False)[:300])

# ---------- bibliography (every reference of the graph) ----------
def bibkey(k):
    return re.sub(r'[^A-Za-z0-9]', '', k.replace('&', 'and'))
with open(os.path.join(P, 'refs_generated.tex'), 'w') as f:
    f.write('\\begin{thebibliography}{99}\n')
    for k, v in REFS.items():
        f.write('\\bibitem{%s} %s\n' % (bibkey(k), tex_escape(v).replace('[verify page numbers]', '\\textit{[page numbers to be verified]}')))
    f.write('\\end{thebibliography}\n')
if '--keys' in sys.argv:
    for k in REFS: print(bibkey(k), '<-', k)
